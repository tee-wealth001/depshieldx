class ParseLockfileDispatchTests(unittest.TestCase):
    def test_dispatches_by_filename(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            path = Path(temp_dir) / "yarn.lock"
            path.write_text(YARN_LOCK_SAMPLE, encoding="utf-8")
            resolved = parse_lockfile(path)

        self.assertEqual(resolved["left-pad"], "1.3.0")

    def test_rejects_unsupported_lockfile_name(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            path = Path(temp_dir) / "composer.lock"
            path.write_text("{}", encoding="utf-8")
            with self.assertRaises(ValueError):
                parse_lockfile(path)


