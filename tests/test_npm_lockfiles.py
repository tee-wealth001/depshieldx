import json
import tempfile
import unittest
from pathlib import Path

from depshieldx.npm_lockfiles import parse_lockfile, parse_package_lock_json, parse_pnpm_lock_yaml, parse_yarn_lock

PACKAGE_LOCK_JSON_SAMPLE = {
    "name": "sample-app",
    "version": "1.0.0",
    "lockfileVersion": 3,
    "requires": True,
    "packages": {
        "": {"name": "sample-app", "version": "1.0.0", "dependencies": {"left-pad": "^1.3.0"}},
        "node_modules/left-pad": {
            "version": "1.3.0",
            "resolved": "https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz",
            "integrity": "sha512-XI5MPzVNApjAyhQzphX8BkmKsKUxD4LdyK24iZeQGinBN9yTQT3bFlCBy/aVx2HrNcqQGsdot8ghrjyrvMCoEA==",
        },
        "node_modules/@babel/core": {
            "version": "8.0.1",
            "resolved": "https://registry.npmjs.org/@babel/core/-/core-8.0.1.tgz",
            "integrity": "sha512-5FgxM4dLQpMJHSiVATk8foW263dVHQHBVpXYiimNECVWG01f4nFyEbQixeT6Mwvg7TayREJ2gpKl3o2RoMdnqw==",
        },
    },
}


class PackageLockJsonParserTests(unittest.TestCase):
    def test_parses_scoped_and_plain_entries_and_skips_root(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            path = Path(temp_dir) / "package-lock.json"
            path.write_text(json.dumps(PACKAGE_LOCK_JSON_SAMPLE), encoding="utf-8")
            resolved = parse_package_lock_json(path)

        self.assertEqual(resolved["left-pad"], "1.3.0")
        self.assertEqual(resolved["@babel/core"], "8.0.1")
        self.assertEqual(len(resolved), 2)

    def test_rejects_lockfile_version_1_without_packages_key(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            path = Path(temp_dir) / "package-lock.json"
            path.write_text(json.dumps({"lockfileVersion": 1, "dependencies": {}}), encoding="utf-8")
            with self.assertRaises(ValueError):
                parse_package_lock_json(path)

