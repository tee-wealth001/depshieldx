class YarnLockParserTests(unittest.TestCase):
    def test_parses_scoped_multi_spec_and_plain_entries(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            path = Path(temp_dir) / "yarn.lock"
            path.write_text(YARN_LOCK_SAMPLE, encoding="utf-8")
            resolved = parse_yarn_lock(path)

        self.assertEqual(resolved["chalk"], "6.0.0")
        self.assertEqual(resolved["left-pad"], "1.3.0")
        self.assertEqual(resolved["@babel/helper-validator-identifier"], "8.0.4")
        self.assertEqual(len(resolved), 3)


